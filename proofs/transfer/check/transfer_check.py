def trace_classes(G):
    vals = []
    tid = []
    for t in G["tr"]:
        if t not in vals:
            vals.append(t)
        tid.append(vals.index(t))
    return vals, tid


def run_enum(G, L, outdir, tag):
    tree, free, red = gauge_fix(L)
    plaqs = [red(p) for p in L["plaqs"]]
    obs_words = [red(p) for p in L["plaqs"]] + [red(w) for (_, w) in L["extra_obs"]]
    vals, tid = trace_classes(G)
    ta, tb = [], []
    for t in G["tr"]:
        assert t.r.denominator == 1 and t.s.denominator == 1, "non-integer trace coordinates"
        ta.append(int(t.r))
        tb.append(int(t.s))
    n = G["n"]
    lines = ["%d %d %d %d" % (n, len(free), len(plaqs), len(obs_words))]
    lines.append(" ".join(str(G["mult"][a][b]) for a in range(n) for b in range(n)))
    lines.append(" ".join(map(str, G["inv"])))
    lines.append(" ".join(map(str, ta)))
    lines.append(" ".join(map(str, tb)))
    lines.append(str(len(vals)) + " " + " ".join(map(str, tid)))
    for w in plaqs + obs_words:
        lines.append(str(len(w)) + " " + " ".join("%d %d" % (i, s) for (i, s) in w))
    jobdir = os.path.join(outdir, "jobs")
    os.makedirs(jobdir, exist_ok=True)
    fin = os.path.join(jobdir, tag + ".in")
    fout = os.path.join(jobdir, tag + ".out")
    with open(fin, "w") as f:
        f.write("\n".join(lines) + "\n")
    subprocess.run([ENUM, fin, fout, "8"], check=True)
    with open(fout, "rb") as f:
        raw = f.read()
    sha = hashlib.sha256(raw).hexdigest()
    act = {}
    obs = {}
    total = None
    for line in raw.decode().splitlines():
        p = line.split()
        if p[0] == "TOTAL":
            total = int(p[1])
        elif p[0] == "ACT":
            act[(int(p[1]), int(p[2]))] = int(p[3])
        elif p[0] == "OBS":
            obs[(int(p[1]), int(p[2]), int(p[3]), int(p[4]))] = int(p[5])
    assert total == n ** len(free)
    return dict(total=total, act=act, obs=obs, vals=vals, sha=sha, free=len(free),
                nobs=len(obs_words))


def enum_series(G, E, N):
    d = G["d"]
    zero = Q(0, 0, d)
    tot = E["total"]
    spow = {}

    def powers(A, B):
        if (A, B) not in spow:
            S = Q(Fr(A, 2), Fr(B, 2), d)  # S = T/2
            p = Q(1, 0, d)
            lst = []
            for _ in range(N + 1):
                lst.append(p)
                p = p * S
            spow[(A, B)] = lst
        return spow[(A, B)]
    z = [zero] * (N + 1)
    for (A, B), c in E["act"].items():
        pw = powers(A, B)
        for nn in range(N + 1):
            z[nn] = z[nn] + pw[nn] * c
    z = [z[nn].div(tot * factorial(nn)) for nn in range(N + 1)]
    # observables: numerator E[(o/2) S^n]/n!; first fold the observable value into a cell weight
    weights = [dict() for _ in range(E["nobs"])]
    for (o, A, B, t), c in E["obs"].items():
        wv = weights[o].get((A, B), zero)
        weights[o][(A, B)] = wv + E["vals"][t] * c
    nums = []
    for o in range(E["nobs"]):
        num = [zero] * (N + 1)
        for (A, B), wv in weights[o].items():
            pw = powers(A, B)
            for nn in range(N + 1):
                num[nn] = num[nn] + pw[nn] * wv
        nums.append([num[nn].div(2 * tot * factorial(nn)) for nn in range(N + 1)])
    return z, nums

