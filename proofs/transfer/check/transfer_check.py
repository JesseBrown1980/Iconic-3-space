def closed_walk_ok(edges, word):
    if not word:
        return True
    pos = None
    start = None
    for (e, s) in word:
        tl, hd = edges[e]
        a, b = (tl, hd) if s == 1 else (hd, tl)
        if pos is None:
            start = a
        elif pos != a:
            return False
        pos = b
    return pos == start


def torus2d(L1, L2):
    sites = [(x, y) for x in range(L1) for y in range(L2)]
    sid = {s: i for i, s in enumerate(sites)}
    edges, eid = [], {}
    for (x, y) in sites:
        for mu, (dx, dy) in enumerate([(1, 0), (0, 1)]):
            hd = ((x + dx) % L1, (y + dy) % L2)
            eid[(x, y, mu)] = len(edges)
            edges.append((sid[(x, y)], sid[hd]))
    plaqs = []
    for (x, y) in sites:
        e1 = eid[(x, y, 0)]
        e2 = eid[((x + 1) % L1, y, 1)]
        e3 = eid[(x, (y + 1) % L2, 0)]
        e4 = eid[(x, y, 1)]
        plaqs.append([(e1, 1), (e2, 1), (e3, -1), (e4, -1)])
    return dict(name="torus%dx%d" % (L1, L2), nv=len(sites), edges=edges, plaqs=plaqs,
                chiE=0, extra_obs=[])


def cube_surface():
    verts = [(a, b, c) for a in (0, 1) for b in (0, 1) for c in (0, 1)]
    vid = {v: i for i, v in enumerate(verts)}
    edges, eid = [], {}
    for v in verts:
        for mu in range(3):
            if v[mu] == 0:
                w = list(v)
                w[mu] = 1
                eid[(v, mu)] = len(edges)
                edges.append((vid[v], vid[tuple(w)]))
    plaqs = []
    for c in range(3):
        m, n_ = [a for a in range(3) if a != c]
        for sval in (0, 1):
            base = [0, 0, 0]
            base[c] = sval
            b = tuple(base)
            bm = list(b)
            bm[m] = 1
            bn = list(b)
            bn[n_] = 1
            plaqs.append([(eid[(b, m)], 1), (eid[(tuple(bm), n_)], 1),
                          (eid[(tuple(bn), m)], -1), (eid[(b, n_)], -1)])
    return dict(name="cube-surface", nv=8, edges=edges, plaqs=plaqs, chiE=2, extra_obs=[])


def pillow():
    edges = [(0, 1), (1, 2), (2, 3), (3, 0)]
    p1 = [(0, 1), (1, 1), (2, 1), (3, 1)]
    p2 = [(3, -1), (2, -1), (1, -1), (0, -1)]
    return dict(name="pillow", nv=4, edges=edges, plaqs=[p1, p2], chiE=2, extra_obs=[])


def stack112():
    """open 3D lattice: two unit cubes stacked along z (2x2x3 sites)."""
    dims = (2, 2, 3)
    sites = [(x, y, z) for x in range(dims[0]) for y in range(dims[1]) for z in range(dims[2])]
    sid = {s: i for i, s in enumerate(sites)}
    edges, eid = [], {}

    def add(v, mu):
        w = list(v)
        w[mu] += 1
        return tuple(w)
    for v in sites:
        for mu in range(3):
            w = add(v, mu)
            if w in sid:
                eid[(v, mu)] = len(edges)
                edges.append((sid[v], sid[w]))
    plaqs = []
    for v in sites:
        for mu in range(3):
            for nu in range(mu + 1, 3):
                vm, vn = add(v, mu), add(v, nu)
                if (v, mu) in eid and (vm, nu) in eid and (vn, mu) in eid and (v, nu) in eid:
                    plaqs.append([(eid[(v, mu)], 1), (eid[(vm, nu)], 1),
                                  (eid[(vn, mu)], -1), (eid[(v, nu)], -1)])
    # 1x2 rectangle in the xz plane at y=0
    rect = [(eid[((0, 0, 0), 0)], 1), (eid[((1, 0, 0), 2)], 1), (eid[((1, 0, 1), 2)], 1),
            (eid[((0, 0, 2), 0)], -1), (eid[((0, 0, 1), 2)], -1), (eid[((0, 0, 0), 2)], -1)]
    return dict(name="stack1x1x2-open", nv=len(sites), edges=edges, plaqs=plaqs, chiE=None,
                extra_obs=[("rect1x2", rect)])


def hypotheses(L):
    P = L["plaqs"]
    h1 = all(len(set(e for e, _ in p)) == len(p) for p in P)
    sets = [set(e for e, _ in p) for p in P]
    maxshare = 0
    for i in range(len(P)):
        for j in range(i + 1, len(P)):
            maxshare = max(maxshare, len(sets[i] & sets[j]))
    h2 = maxshare <= 1
    # H2': for every link l and plaquette p containing l, p has a link l' != l that occurs
    # exactly once in p and lies in no other plaquette containing l.
    h2p = True
    for l in range(len(L["edges"])):
        star = [i for i in range(len(P)) if l in sets[i]]
        for i in star:
            others = set()
            for j in star:
                if j != i:
                    others |= sets[j]
            ok = False
            for (e, _) in P[i]:
                if e != l and sum(1 for (f, _) in P[i] if f == e) == 1 and e not in others:
                    ok = True
            if not ok:
                h2p = False
    return dict(H1=int(h1), H2=int(h2), H2p=int(h2p), maxshare=maxshare)


def gauge_fix(L):
    nv, edges = L["nv"], L["edges"]
    adj = [[] for _ in range(nv)]
    for e, (a, b) in enumerate(edges):
        if a != b:
            adj[a].append((e, b))
            adj[b].append((e, a))
    seen = [False] * nv
    seen[0] = True
    tree = set()
    stack = [0]
    while stack:
        v = stack.pop()
        for (e, w) in adj[v]:
            if not seen[w]:
                seen[w] = True
                tree.add(e)
                stack.append(w)
    assert all(seen), "lattice graph not connected"
    free = [e for e in range(len(edges)) if e not in tree]
    fidx = {e: i for i, e in enumerate(free)}

    def red(word):
        return [(fidx[e], s) for (e, s) in word if e not in tree]
    return tree, free, red

