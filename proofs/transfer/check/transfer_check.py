def s_mul(a, b, N, zero):
    c = [zero] * (N + 1)
    for i in range(N + 1):
        if a[i].iszero():
            continue
        for j in range(N + 1 - i):
            c[i + j] = c[i + j] + a[i] * b[j]
    return c


def s_log(z, N, zero):
    assert z[0] == 1
    lg = [zero] * (N + 1)
    for n in range(1, N + 1):
        acc = z[n] * n
        for k in range(1, n):
            acc = acc - lg[k] * k * z[n - k]
        lg[n] = acc.div(n)
    return lg


def s_div(a, b, N, zero):
    assert b[0] == 1
    c = [zero] * (N + 1)
    for n in range(N + 1):
        acc = a[n]
        for k in range(1, n + 1):
            acc = acc - b[k] * c[n - k]
        c[n] = acc
    return c


def s_pow(a, e, N, zero, one):
    r = [one] + [zero] * N
    for _ in range(e):
        r = s_mul(r, a, N, zero)
    return r


def haar_surface_Z(chiE, F, N, d):
    zero, one = Q(0, 0, d), Q(1, 0, d)
    Z = [zero] * (N + 1)
    for k in range(0, KMAX):
        if k * F > N:
            break
        dk = k + 1
        a = [Q(Fr(MT[n][k], (2 ** n) * factorial(n) * dk), 0, d) for n in range(N + 1)]
        term = s_pow(a, F, N, zero, one)
        fac = Fr(dk) ** chiE
        Z = [Z[i] + term[i] * fac for i in range(N + 1)]
    return Z


def q8_glue_Z(G, chiE, F, N):
    d = G["d"]
    zero, one = Q(0, 0, d), Q(1, 0, d)
    els = G["elems"]

    def in_axis(q, ax):
        return all(q[c].iszero() for c in (1, 2, 3) if c != ax)
    chars = [([Q(1, 0, d)] * len(els), 1)]
    for ax in (1, 2, 3):
        chars.append(([Q(1 if in_axis(q, ax) else -1, 0, d) for q in els], 1))
    chars.append((list(G["tr"]), 2))
    # orthonormality check
    for (c1, _) in chars:
        for (c2, _) in chars:
            s = Q(0, 0, d)
            for g in range(len(els)):
                s = s + c1[g] * c2[g]
            s = s.div(len(els))
            assert s == (1 if c1 is c2 else 0)
    Z = [zero] * (N + 1)
    for (ch, dim) in chars:
        a = []
        for n in range(N + 1):
            s = Q(0, 0, d)
            for g in range(len(els)):
                p = ch[g]
                for _ in range(n):
                    p = p * G["tr"][g]
                s = s + p
            a.append(s.div(len(els) * (2 ** n) * factorial(n) * dim))
        term = s_pow(a, F, N, zero, one)
        fac = Fr(dim) ** chiE
        Z = [Z[i] + term[i] * fac for i in range(N + 1)]
    return Z

