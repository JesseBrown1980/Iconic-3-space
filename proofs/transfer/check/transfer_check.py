def mult_table(nmax, kmax):
    """m[n][k] = multiplicity of V_{k/2} in V_{1/2}^{(x)n}."""
    m = [[0] * (kmax + 2) for _ in range(nmax + 1)]
    m[0][0] = 1
    for n in range(nmax):
        for k in range(kmax + 1):
            v = m[n][k + 1]
            if k >= 1:
                v += m[n][k - 1]
            m[n + 1][k] = v
    return m


KMAX = 16
MT = mult_table(16, KMAX)


def haar_moment(n):
    return Fr(MT[n][0])


def dfact(k):
    r = 1
    while k > 1:
        r *= k
        k -= 2
    return r


def haar_sphere_monomial(a):
    if any(x % 2 for x in a):
        return Fr(0)
    b = [x // 2 for x in a]
    B = sum(b)
    num = 1
    for bi in b:
        num *= dfact(2 * bi - 1)
    return Fr(num, (2 ** B) * factorial(B + 1))


def group_design_data(G, deg_cap):
    n = G["n"]
    d = G["d"]
    tr = G["tr"]
    # trace moments
    mom = []
    for k in range(0, 15):
        s = Q(0, 0, d)
        for t in tr:
            p = Q(1, 0, d)
            for _ in range(k):
                p = p * t
            s = s + p
        mom.append(s.div(n))
    # dims of invariants iota_k = E_G[chi_{k/2}]
    chis = [[Q(1, 0, d) for _ in tr], list(tr)]
    for k in range(1, 15):
        chis.append([tr[g] * chis[k][g] - chis[k - 1][g] for g in range(n)])
    iota = []
    for k in range(0, 15):
        s = Q(0, 0, d)
        for g in range(n):
            s = s + chis[k][g]
        iota.append(s.div(n))

    def first_fail(seq):
        for k in range(1, len(seq)):
            if not seq[k]:
                return k - 1
        return len(seq) - 1
    t_mom = first_fail([True] + [mom[k] == haar_moment(k) for k in range(1, 15)])
    t_dim = first_fail([True] + [iota[k].iszero() for k in range(1, 15)])
    # direct DGS check: all monomials in the 4 real coordinates of degree <= deg
    pw = []
    for q in G["elems"]:
        rows = []
        for c in q:
            r = [Q(1, 0, d)]
            for _ in range(deg_cap):
                r.append(r[-1] * c)
            rows.append(r)
        pw.append(rows)
    t_mono = None
    for deg in range(1, deg_cap + 1):
        ok = True
        for a in itertools.product(range(deg + 1), repeat=4):
            if sum(a) != deg:
                continue
            s = Q(0, 0, d)
            for rows in pw:
                s = s + rows[0][a[0]] * rows[1][a[1]] * rows[2][a[2]] * rows[3][a[3]]
            if not (s.div(n) == haar_sphere_monomial(a)):
                ok = False
                break
        if not ok:
            t_mono = deg - 1
            break
    if t_mono is None:
        t_mono = deg_cap  # meaning: >= deg_cap
    return dict(mom=mom, iota=iota, t_mom=t_mom, t_dim=t_dim, t_mono=t_mono)

