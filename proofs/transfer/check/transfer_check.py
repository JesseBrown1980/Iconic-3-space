class Q:
    __slots__ = ("r", "s", "d")

    def __init__(self, r, s=0, d=2):
        self.r = Fr(r)
        self.s = Fr(s)
        self.d = d

    def _c(self, o):
        return o if isinstance(o, Q) else Q(o, 0, self.d)

    def __add__(self, o):
        o = self._c(o)
        return Q(self.r + o.r, self.s + o.s, self.d)

    __radd__ = __add__

    def __neg__(self):
        return Q(-self.r, -self.s, self.d)

    def __sub__(self, o):
        o = self._c(o)
        return Q(self.r - o.r, self.s - o.s, self.d)

    def __rsub__(self, o):
        return self._c(o) - self

    def __mul__(self, o):
        if not isinstance(o, Q):
            o = Fr(o)
            return Q(self.r * o, self.s * o, self.d)
        return Q(self.r * o.r + self.d * self.s * o.s, self.r * o.s + self.s * o.r, self.d)

    __rmul__ = __mul__

    def div(self, k):
        k = Fr(k)
        return Q(self.r / k, self.s / k, self.d)

    def __eq__(self, o):
        o = self._c(o)
        return self.r == o.r and self.s == o.s

    def __hash__(self):
        return hash((self.r, self.s))

    def iszero(self):
        return self.r == 0 and self.s == 0

    def __str__(self):
        if self.s == 0:
            return str(self.r)
        return "%s%+s*sqrt%d" % (self.r, self.s, self.d)


def qmul(a, b):
    a0, a1, a2, a3 = a
    b0, b1, b2, b3 = b
    return (a0 * b0 - a1 * b1 - a2 * b2 - a3 * b3,
            a0 * b1 + a1 * b0 + a2 * b3 - a3 * b2,
            a0 * b2 - a1 * b3 + a2 * b0 + a3 * b1,
            a0 * b3 + a1 * b2 - a2 * b1 + a3 * b0)


def qkey(q):
    return tuple((c.r, c.s) for c in q)


def make_group(name, d, gens_raw):
    """gens_raw: list of 4-tuples of (r, s) pairs meaning r + s*sqrt(d)."""
    gens = [tuple(Q(r, s, d) for (r, s) in g) for g in gens_raw]
    one = (Q(1, 0, d), Q(0, 0, d), Q(0, 0, d), Q(0, 0, d))
    elems = [one]
    index = {qkey(one): 0}
    frontier = [one]
    while frontier:
        new = []
        for a in frontier:
            for g in gens:
                c = qmul(a, g)
                kk = qkey(c)
                if kk not in index:
                    index[kk] = len(elems)
                    elems.append(c)
                    new.append(c)
        frontier = new
    n = len(elems)
    for q in elems:
        nrm = q[0] * q[0] + q[1] * q[1] + q[2] * q[2] + q[3] * q[3]
        assert nrm == 1, "non-unit element in " + name
    mult = [[index[qkey(qmul(a, b))] for b in elems] for a in elems]  # KeyError = not closed
    inv = [index[qkey((q[0], -q[1], -q[2], -q[3]))] for q in elems]
    tr = [q[0] * 2 for q in elems]
    return dict(name=name, d=d, n=n, elems=elems, mult=mult, inv=inv, tr=tr)


